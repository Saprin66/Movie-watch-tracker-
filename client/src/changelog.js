const SEEN_KEY = "mg-changelog-seen";

const read = (key) => {
  try {
    return localStorage.getItem(key);
  } catch {
    return null;
  }
};

const write = (key, value) => {
  try {
    localStorage.setItem(key, value);
  } catch {
    /* без хранилища подсказка может показаться снова */
  }
};

// Есть ли в списке изменений то, что человек ещё не открывал
export const hasUnseenChanges = () => read(SEEN_KEY) !== APP_VERSION;

export const markChangesSeen = () => write(SEEN_KEY, APP_VERSION);

// Версия, с которой сайт обновился с прошлого захода (null — не обновлялся или первый заход).
// Запоминает текущую версию, поэтому вернёт её только один раз.
export function takeUpdatedFrom() {
  const LAST_KEY = "mg-last-version";
  const last = read(LAST_KEY);
  write(LAST_KEY, APP_VERSION);
  // При первом заходе (или до появления списка изменений) подсказку не показываем:
  // о новом хватит точки на аватарке
  return last && last !== APP_VERSION ? last : null;
}
